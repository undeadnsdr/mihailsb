/** Направление работ: карточка в меню услуг + детальный блок с прайсом */
export type Service = {
  /** Якорь на странице и ключ фильтра в галерее */
  slug: string
  /** Полное название для заголовка детального блока */
  title: string
  /** Короткое имя для навигации, фильтров и выпадающих списков форм */
  navTitle: string
  /** Одна строка в карточке меню услуг */
  short: string
  /** Цена «от» числом, без знака рубля — он приходит из priceUnit.
   *  Разряды расставляет formatNumber, см. хелперы внизу файла */
  priceFrom: number
  /** Единица измерения вместе со знаком рубля: `₽/м²`, `₽/точка` */
  priceUnit: string
  image: string
  imageAlt: string
  /** Слайд-шоу в детальном блоке направления. Первый кадр обычно повторяет
   *  image/imageAlt выше — он же используется отдельно в карточке меню
   *  услуг, где слайд-шоу не нужно */
  images: { src: string; alt: string }[]
  /** Абзац-оффер в детальном блоке */
  offer: string
  /** Что входит в направление */
  bullets: string[]
  /** Этапы работ именно этого направления */
  steps: { title: string; text: string }[]
  /** Прайс-лист подгруппами, как в исходном объявлении.
   *  from: null — цена договорная, тогда текст берётся из note */
  priceGroups: { title: string; rows: { name: string; from: number | null; note?: string }[] }[]
}

