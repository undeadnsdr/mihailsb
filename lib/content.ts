/**
 * Демонстрационные макеты для галереи.
 * Это не скриншоты чужих сайтов: макеты собраны вёрсткой на этой же странице,
 * поэтому текст в них читаемый на любом экране и не весит ни байта.
 *
 * blurRegions — слой размытия поверх макета в процентах от его размера.
 * Когда появятся реальные скриншоты клиентов, названия закрываются здесь,
 * а не в графическом редакторе: правится в одном месте и не съезжает.
 */
/**
 * Оформление демо-сайта конкретного проекта.
 *
 * Раньше все семь макетов рисовались токенами этого сайта (bg-card,
 * text-primary) и одним шаблоном — на всех экранах слайдшоу показывался
 * один и тот же сайт с подменёнными подписями. Здесь у каждого проекта
 * своя палитра и свой каркас первого экрана, поэтому «Кровля» и «Кухни»
 * читаются как два разных сайта двух разных студий, а не как одна тема
 * с другим текстом. Палитра и layout живут на уровне проекта, а не
 * устройства: один и тот же сайт в пяти адаптациях обязан остаться собой.
 *
 * layout — каркас первого экрана:
 *  overlay-left   — фото на весь экран, заголовок слева (классический лендинг)
 *  overlay-bottom — фото на весь экран, крупный заголовок прижат к низу
 *  split          — заголовок на цветной половине, фото во второй половине
 *  centered       — фото, заголовок по центру, под ним строка преимуществ
 */

/** Блоки «тела» лендинга. Порядок задаётся проектом — см. WorkSite.blocks */
export type WorkBlock = 'services' | 'price' | 'stats' | 'gallery' | 'steps' | 'review'

export type WorkSite = {
  layout: 'overlay-left' | 'overlay-bottom' | 'split' | 'centered'
  /**
   * Порядок блоков ниже первого экрана — у каждого проекта свой.
   * Раньше порядок выводился из layout, и у семи проектов было три
   * варианта на всех: сайты с одинаковым каркасом первого экрана
   * дальше шли блок в блок. Здесь это просто список, поэтому две
   * «кровли» не обязаны рассказывать о себе в одной последовательности:
   * где решает смета — цена идёт первой, где решает картинка — галерея.
   */
  blocks: readonly WorkBlock[]
  /** Шапка: подпись слева / логотип по центру / телефон крупно справа */
  header: 'plain' | 'centered' | 'contact'
  /** Услуги: плитки с иконками / чипы в строку / нумерованные строки */
  services: 'cards' | 'chips' | 'rows'
  /** Работы: три равных кадра / мозаика 1+2 / лента с обрезкой у края */
  gallery: 'grid' | 'mosaic' | 'strip'
  /** Цифры: плашка акцентным цветом / без фона, по линии сверху */
  stats: 'band' | 'plain'
  /** Фон страницы демо-сайта */
  bg: string
  /** Карточки и панели поверх фона */
  surface: string
  text: string
  muted: string
  line: string
  primary: string
  primaryFg: string
  /** Тёмная (или контрастная фону) плашка под цену и акценты */
  accent: string
  accentFg: string
  /** Затемнение поверх фотографии первого экрана — под светлый текст */
  heroScrim: string
}

