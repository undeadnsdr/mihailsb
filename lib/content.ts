/**
 * Русское согласование числительного с существительным.
 *
 * Нужно из-за строки «12 позиций» в шапке свёрнутого прайса: число там
 * считается из длины массива, а «12 позиция» в интерфейсе читается как
 * недоделка. Обычный тернарник n === 1 тут не работает — в русском три
 * формы, и выбор идёт по последним двум разрядам (11–14 — особый случай).
 */
function plural(n: number, one: string, few: string, many: string): string {
  const mod100 = n % 100
  if (mod100 >= 11 && mod100 <= 14) return many
  const mod10 = n % 10
  if (mod10 === 1) return one
  if (mod10 >= 2 && mod10 <= 4) return few
  return many
}

