/**
 * Разряды числа узким нера��рывным пробелом (U+202F). Обычный пробел
 * разрешает переносу разорвать «1 045» на две строки, и в таблице
 * появляется висячая цифра.
 */
export function formatNumber(value: number): string {
  return value.toLocaleString('ru-RU').replace(/\s/g, '\u202f')
}

/**
 * Цена со знаком рубля — для мест, где единица не выводится отдельно
 * (строки прайс-листа). Там, где рядом стоит подпись вида «₽/м²»,
 * нужен formatNumber, иначе знак рубля печатается дважды.
 */
export function formatPrice(value: number): string {
  return `${formatNumber(value)}\u202f₽`
}

/** Ссылка на Telegram с предзаполненным текстом сообщения */
export function telegramLink(text: string = telegramMessage): string {
  return `${site.telegramUrl}?text=${encodeURIComponent(text)}`
}
